test('AI cave HTTP actions require host auth, publish to overlays, and retain the request cap', async t => {
    const originalFetch = globalThis.fetch;
    let calls = 0;
    t.mock.method(globalThis, 'fetch', async (url: any, options: any) => {
        if (url !== 'https://api.openai.com/v1/responses') return originalFetch(url, options);
        calls++;
        const ideas = JSON.parse(JSON.parse(options.body).input).ideas;
        const pixels = Array(16).fill('..122222222223..');
        const cave = { name: 'Ice Hive', enemyName: 'Ice bee', cacheName: 'Frozen box', findName: 'Toast charm', rule: 'gaps', enemyPixels: pixels, findPixels: pixels, contributions: ideas.map((i: any) => ({ messageId: i.messageId, feature: i.idea })) };
        return new Response(JSON.stringify({ status: 'completed', output: [{ content: [{ type: 'output_text', text: JSON.stringify(cave) }] }], usage: { input_tokens: 100, output_tokens: 200 } }));
    });
    await withApp(async (app, url) => {
        const headers = { Origin: url, 'Content-Type': 'application/json', Cookie: '' };
        const post = (body: unknown) => fetch(`${url}/api/action`, { method: 'POST', headers, body: JSON.stringify(body) });
        const args = { sessionId: app.game.id, team: 'a' };
        assert.equal((await post({ ...args, action: 'cave-generate' })).status, 401);
        const auth = await fetch(`${url}/api/session`, { method: 'POST', headers, body: '{}' });
        headers.Cookie = auth.headers.get('set-cookie')!.split(';')[0]!;
        assert.equal((await post({ ...args, action: 'cave-ideas', ideas: ['one', '', 'three'] })).status, 400);
        assert.equal(app.game.caves.pools.a.length, 0);
        assert.equal((await post({ ...args, action: 'cave-ideas', ideas: ['bees', 'ice', 'toaster'] })).status, 200);
        assert.equal(calls, 0);
        assert.equal((await post({ ...args, action: 'cave-generate' })).status, 200);
        await new Promise(resolve => setImmediate(resolve));
        const state = await (await fetch(`${url}/api/state`)).json() as any;
        assert.equal(state.state.caves.ready.b.name, 'Ice Hive');
        assert.equal(state.capabilities.ai.requests, 1);
        assert.equal((await post({ ...args, action: 'cave-generate' })).status, 400);
        assert.equal(calls, 1);
        const abort = new AbortController();
        const stream = await fetch(`${url}/api/events`, { signal: abort.signal });
        const chunk = await stream.body!.getReader().read();
        const event = JSON.parse(new TextDecoder().decode(chunk.value).split('\n')[0]!.slice(6));
        assert.deepEqual(event.state.caves.ready, state.state.caves.ready);
        abort.abort();
        app.game.setMode('demo');
        assert.equal((await post({ ...args, action: 'cave-generate' })).status, 400);
        assert.deepEqual(app.game.caves.ready, {});
    }, { OPENAI_API_KEY: 'mock-test-key', AI_MAX_REQUESTS: '1' });
});
