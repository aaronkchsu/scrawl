test('Hype Train upgrades are monotonic, channel scoped, queued bonus survives train ending, late begin is ignored', () => {
    const { game, advance, now } = fixture();
    game.configure({ slots: 1 });
    game.dig('demo:peach');
    game.dig('demo:noodle');
    const event = { id: 'train', team: 'a' as const, kind: 'progress' as const, level: 3, startedAt: now(), expiresAt: now() + 90000 };
    game.receiveHype(event, true);
    assert.equal(game.queue[0]!.multiplier, 3);
    assert.equal(game.runs[0]!.multiplier, 3);
    game.receiveHype({ ...event, kind: 'begin', level: 1 }, true);
    assert.equal(game.hype.a!.level, 3);
    game.receiveHype({ ...event, kind: 'end' }, true);
    game.receiveHype(event, true);
    assert.equal(game.hype.a, undefined);
    advance();
    advance();
    advance();
    let r = game.runs[0]!;
    game.choose(r.playerId, r.id, 'keep');
    advance(6000);
    assert.equal(game.runs[0]!.playerId, 'demo:noodle');
    assert.equal(game.runs[0]!.multiplier, 3);
    game.receiveHype({ ...event, id: 'new', team: 'b' }, true);
    assert.equal(game.runs[0]!.multiplier, 3);
});
test('live chat identity, duplicate handling, demo isolation, automatic safe keep and session reset', () => {
    const { game, advance } = fixture();
    const message = { id: 'message', team: 'a' as const, userId: '42', name: 'Viewer', text: '!dig', source: 'twitch' as const };
    game.ingest(message);
    assert.equal(game.runs.length, 0);
    assert.throws(() => game.setMode('live'));
    game.setConnection('a', 'channel', 'connected', 'Connected');
    game.setMode('live');
    assert.equal(game.players.size, 0);
    assert.throws(() => game.join('demo:fake', 'Fake', 'a'));
    game.ingest(message);
    game.ingest(message);
    assert.equal(game.runs.length, 1);
    assert.equal(game.queue.length, 0);
    advance();
    advance();
    advance();
    const r = game.runs[0]!;
    assert.equal(r.phase, 'choice');
    advance(45000);
    assert.equal(r.phase, 'banked');
    const oldId = game.id;
    game.setMode('demo');
    assert.notEqual(game.id, oldId);
    assert.equal(game.runs.length, 0);
    assert.throws(() => game.choose('twitch:42', r.id, 'risk'));
    advance(100000);
    assert.equal(game.runs.length, 0);
    assert.ok(game.store.profiles['twitch:42']!.ore > 0);
    assert.equal(game.players.has('twitch:42'), false);
});
test('new viewers can auto-queue, repeated joins do not queue again, settings validate atomically', () => {
    const { game } = fixture();
    game.setConnection('a', 'channel', 'connected', 'Connected');
    game.setMode('live');
    game.configure({ autoDigOnJoin: true });
    game.ingest({ id: '1', team: 'a', userId: '1', name: 'One', text: '!join', source: 'twitch' });
    game.ingest({ id: '2', team: 'a', userId: '1', name: 'One', text: '!join', source: 'twitch' });
    assert.equal(game.runs.length, 1);
    assert.equal(game.queue.length, 0);
    assert.throws(() => game.configure({ slots: 2, avatarSize: 500 }));
    assert.equal(game.settings.slots, 3);
});
